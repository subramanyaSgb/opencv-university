// Builds apps/web/generated/content-index.ts from content/course.json and module.json files,
// and copies assets/images/generated/* to apps/web/public/images/.
// Runs automatically before `npm run dev` and `npm run build`.
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

/** Pulls `minutes` out of a chapter's `export const meta = {...}` source text, without executing the MDX. */
export function extractMinutes(mdxSource) {
  const m = mdxSource.match(/export const meta\s*=\s*\{[\s\S]*?minutes:\s*(\d+)/);
  return m ? Number(m[1]) : undefined;
}

/** Pulls the chapter's one `<Definition term="...">...</Definition>` (chapter shape section 1). */
export function extractDefinition(mdxSource) {
  const m = mdxSource.match(/<Definition term="([^"]+)">([\s\S]*?)<\/Definition>/);
  return m ? { term: m[1], definition: m[2].trim() } : undefined;
}

function build() {
  const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
  const course = read("content/course.json");

  const loaders = [];
  const glossary = [];
  const parts = course.parts.map((part) => ({
    ...part,
    modules: part.modules.map((moduleId) => {
      const mod = read(`content/${part.id}/${moduleId}/module.json`);
      return {
        id: moduleId,
        number: mod.number,
        title: mod.title,
        summary: mod.summary,
        chapters: mod.chapters.map((ch) => {
          const key = `${part.id}/${moduleId}/${ch.slug}`;
          const mdxPath = join(root, "content", `${key}.mdx`);
          const available = existsSync(mdxPath);
          const href = `/learn/${key}`;
          if (available) {
            loaders.push(`  ${JSON.stringify(key)}: () => import("../../../content/${key}.mdx") as Promise<unknown> as Promise<ChapterModule>,`);
            const source = readFileSync(mdxPath, "utf8");
            const minutes = extractMinutes(source);
            const def = extractDefinition(source);
            if (def) glossary.push({ ...def, chapterNumber: ch.number, chapterTitle: ch.title, chapterHref: href });
            return { ...ch, href, available, ...(minutes !== undefined ? { minutes } : {}) };
          }
          return { ...ch, href, available };
        }),
      };
    }),
  }));
  glossary.sort((a, b) => a.term.localeCompare(b.term));

  const out = `// GENERATED by scripts/build-content-index.mjs. Do not edit.
import type { ComponentType } from "react";
import type { ChapterMeta, CourseIndex, GlossaryEntry } from "../lib/course-types";

export const course: CourseIndex = ${JSON.stringify({ title: course.title, parts }, null, 2)};

export const glossary: GlossaryEntry[] = ${JSON.stringify(glossary, null, 2)};

type ChapterModule = { default: ComponentType; meta: ChapterMeta };

export const chapterLoaders: Record<string, () => Promise<ChapterModule>> = {
${loaders.join("\n")}
};
`;
  mkdirSync(join(root, "apps/web/generated"), { recursive: true });
  writeFileSync(join(root, "apps/web/generated/content-index.ts"), out);

  const imgSrc = join(root, "assets/images/generated");
  if (existsSync(imgSrc)) cpSync(imgSrc, join(root, "apps/web/public/images"), { recursive: true });
  console.log(`content index: ${loaders.length} chapter(s) available, ${glossary.length} glossary term(s)`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  build();
}
